import PDFDocument from "pdfkit";

interface AnalyticsData {
  overview: {
    total_applications: number;
    submitted: number;
    interviews: number;
    offers: number;
    rejections: number;
    response_rate: number;
    avg_response_time_days: number | null;
  };
  pipeline: Record<string, number>;
  recent_activity: {
    last_30_days: number;
    submitted_last_30_days: number;
  };
}

/**
 * Generate a PDF report of application analytics.
 */
export async function generateAnalyticsPdf(
  data: AnalyticsData,
  userName?: string,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "LETTER",
      margins: { top: 50, bottom: 50, left: 50, right: 50 },
      info: {
        Title: "Application Analytics Report",
        Author: "StackScout AI",
        Subject: "Job Application Analytics",
      },
    });

    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const font = "Helvetica";

    // Header
    doc.font(font).fontSize(24).fillColor("#000000").text("Application Analytics Report", {
      align: "center",
    });
    doc.moveDown(0.5);

    if (userName) {
      doc.font(font).fontSize(12).fillColor("#666666").text(`Prepared for: ${userName}`, {
        align: "center",
      });
    }

    doc.font(font).fontSize(10).fillColor("#999999").text(
      `Generated on ${new Date().toLocaleDateString()}`,
      { align: "center" },
    );

    doc.moveDown(1);
    doc.moveTo(50, doc.y).lineTo(562, doc.y).strokeColor("#cccccc").lineWidth(0.5).stroke();
    doc.moveDown(1);

    // Overview Section
    doc.font(font).fontSize(16).fillColor("#000000").text("Overview");
    doc.moveDown(0.5);

    const overviewItems = [
      { label: "Total Applications", value: data.overview.total_applications },
      { label: "Submitted", value: data.overview.submitted },
      { label: "Interviews", value: data.overview.interviews },
      { label: "Offers", value: data.overview.offers },
      { label: "Rejections", value: data.overview.rejections },
      { label: "Response Rate", value: `${data.overview.response_rate}%` },
      {
        label: "Avg. Response Time",
        value: data.overview.avg_response_time_days
          ? `${data.overview.avg_response_time_days} days`
          : "N/A",
      },
    ];

    overviewItems.forEach((item) => {
      doc.font(font).fontSize(11).fillColor("#333333");
      doc.text(`${item.label}:`, { continued: true });
      doc.font(font).fontSize(11).fillColor("#000000").text(` ${item.value}`);
      doc.moveDown(0.3);
    });

    doc.moveDown(1);

    // Pipeline Section
    doc.font(font).fontSize(16).fillColor("#000000").text("Pipeline Breakdown");
    doc.moveDown(0.5);

    const pipelineEntries = Object.entries(data.pipeline).filter(([, v]) => v > 0);
    if (pipelineEntries.length === 0) {
      doc.font(font).fontSize(11).fillColor("#666666").text("No pipeline data available.");
    } else {
      pipelineEntries.forEach(([status, count]) => {
        const label = status.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
        doc.font(font).fontSize(11).fillColor("#333333");
        doc.text(`${label}:`, { continued: true });
        doc.font(font).fontSize(11).fillColor("#000000").text(` ${count}`);
        doc.moveDown(0.3);
      });
    }

    doc.moveDown(1);

    // Recent Activity Section
    doc.font(font).fontSize(16).fillColor("#000000").text("Recent Activity (Last 30 Days)");
    doc.moveDown(0.5);

    doc.font(font).fontSize(11).fillColor("#333333");
    doc.text(`Applications submitted: ${data.recent_activity.submitted_last_30_days}`);
    doc.text(`Total activity: ${data.recent_activity.last_30_days}`);

    doc.moveDown(2);

    // Footer
    doc.font(font).fontSize(9).fillColor("#999999").text(
      "This report was generated by StackScout AI. For informational purposes only.",
      { align: "center" },
    );

    doc.end();
  });
}
