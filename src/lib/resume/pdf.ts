import PDFDocument from "pdfkit";
import type { ResumeTemplate } from "./templates";

export interface ResumeBuilderSection {
  id: string;
  type: "experience" | "education" | "skills" | "summary";
  title: string;
  content: string;
  items?: string[];
}

export interface ResumeData {
  name: string;
  email: string;
  phone: string;
  location: string;
  linkedin?: string;
  website?: string;
  summary: string;
  sections: ResumeBuilderSection[];
  template: ResumeTemplate;
}

/**
 * Generate an ATS-optimized PDF resume.
 * Supports both structured data (ResumeData) and legacy text format.
 */
export async function generateResumePdf(
  data: ResumeData | string,
  candidateName?: string,
): Promise<Buffer> {
  // If data is a string, use the legacy text-based generation
  if (typeof data === "string") {
    return generateResumePdfFromText(data, candidateName);
  }

  // Otherwise, use the structured data generation
  return generateResumePdfFromData(data);
}

/**
 * Generate PDF from structured resume data.
 */
async function generateResumePdfFromData(data: ResumeData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "LETTER",
      margins: { top: 50, bottom: 50, left: 50, right: 50 },
      info: {
        Title: `${data.name} - Resume`,
        Author: data.name,
        Subject: "Resume",
        Keywords: "resume, cv, ats",
      },
    });

    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const font = "Helvetica";
    const primaryColor = data.template.colors.primary;
    const secondaryColor = data.template.colors.secondary;

    // Header
    doc.font(font).fontSize(24).fillColor(primaryColor).text(data.name, {
      align: "center",
    });
    doc.moveDown(0.3);

    // Contact info
    const contactParts = [
      data.email,
      data.phone,
      data.location,
      data.linkedin,
      data.website,
    ].filter(Boolean);

    if (contactParts.length > 0) {
      doc.font(font).fontSize(10).fillColor(secondaryColor).text(
        contactParts.join(" | "),
        { align: "center" },
      );
    }

    doc.moveDown(1);
    doc.moveTo(50, doc.y).lineTo(562, doc.y).strokeColor("#cccccc").lineWidth(0.5).stroke();
    doc.moveDown(1);

    // Summary section
    if (data.summary) {
      doc.font(font).fontSize(14).fillColor(primaryColor).text("Professional Summary");
      doc.moveDown(0.3);
      doc.font(font).fontSize(11).fillColor("#333333").text(data.summary, {
        align: "left",
        width: 512,
      });
      doc.moveDown(1);
    }

    // Custom sections
    for (const section of data.sections) {
      doc.font(font).fontSize(14).fillColor(primaryColor).text(section.title);
      doc.moveDown(0.3);

      if (section.items && section.items.length > 0) {
        for (const item of section.items) {
          doc.font(font).fontSize(11).fillColor("#333333").text(`• ${item}`, {
            align: "left",
            width: 512,
          });
          doc.moveDown(0.2);
        }
      } else if (section.content) {
        doc.font(font).fontSize(11).fillColor("#333333").text(section.content, {
          align: "left",
          width: 512,
        });
      }

      doc.moveDown(1);
    }

    // Footer
    doc.font(font).fontSize(9).fillColor("#999999").text(
      `Generated by StackScout AI on ${new Date().toLocaleDateString()}`,
      { align: "center" },
    );

    doc.end();
  });
}

/**
 * Generate an ATS-optimized PDF resume from structured text.
 * Uses standard fonts, clear sections, and ATS-friendly formatting.
 * @deprecated Use generateResumePdf(data: ResumeData) instead
 */
export async function generateResumePdfFromText(
  resumeText: string,
  candidateName?: string,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "LETTER",
      margins: { top: 50, bottom: 50, left: 50, right: 50 },
      info: {
        Title: `${candidateName ?? "Resume"} - Resume`,
        Author: candidateName ?? "Candidate",
        Subject: "Resume",
        Keywords: "resume, cv, ats",
      },
    });

    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    // Standard ATS-friendly font
    const font = "Helvetica";

    // Parse resume text into sections
    const sections = parseResumeSections(resumeText);

    // Header
    doc.font(font).fontSize(20).fillColor("#000000").text(candidateName ?? "Resume", {
      align: "center",
    });
    doc.moveDown(0.5);

    // Contact info line
    if (sections.contact) {
      doc.font(font).fontSize(10).fillColor("#444444").text(sections.contact, {
        align: "center",
      });
      doc.moveDown(1);
    }

    // Divider
    doc.moveTo(50, doc.y).lineTo(562, doc.y).strokeColor("#cccccc").lineWidth(0.5).stroke();
    doc.moveDown(0.5);

    // Sections
    for (const section of sections.sections) {
      // Section header
      doc.font(font).fontSize(14).fillColor("#000000").text(section.title.toUpperCase());
      doc.moveDown(0.3);

      // Section content
      doc.font(font).fontSize(10).fillColor("#333333");

      for (const item of section.items) {
        if (item.type === "heading") {
          doc.font(font).fontSize(11).fillColor("#000000").text(item.text);
          doc.moveDown(0.2);
        } else if (item.type === "subheading") {
          doc.font(font).fontSize(10).fillColor("#444444").text(item.text);
          doc.moveDown(0.1);
        } else if (item.type === "bullet") {
          doc.font(font).fontSize(10).fillColor("#333333").text(`• ${item.text}`, {
            indent: 10,
          });
          doc.moveDown(0.1);
        } else if (item.type === "text") {
          doc.font(font).fontSize(10).fillColor("#333333").text(item.text, {
            width: 512,
          });
          doc.moveDown(0.2);
        }
      }

      doc.moveDown(0.5);
    }

    doc.end();
  });
}

interface ResumeSection {
  title: string;
  items: ResumeItem[];
}

interface ResumeItem {
  type: "heading" | "subheading" | "bullet" | "text";
  text: string;
}

interface ParsedResume {
  contact?: string;
  sections: ResumeSection[];
}

/** Parse resume text into structured sections for PDF generation. */
function parseResumeSections(text: string): ParsedResume {
  const lines = text.split("\n").map((l) => l.trim()).filter(Boolean);
  const sections: ResumeSection[] = [];
  let currentSection: ResumeSection | null = null;
  let contact: string | undefined;

  const sectionKeywords = [
    "professional summary",
    "summary",
    "core skills",
    "skills",
    "technical skills",
    "professional experience",
    "experience",
    "work experience",
    "education",
    "certifications",
    "projects",
    "awards",
    "publications",
  ];

  for (const line of lines) {
    const lower = line.toLowerCase();

    // Check if this is a section header
    const isSectionHeader = sectionKeywords.some(
      (kw) => lower === kw || lower === kw.toUpperCase() || lower === kw.replace(/\b\w/g, (c) => c.toUpperCase()),
    );

    if (isSectionHeader) {
      // Start new section
      if (currentSection) sections.push(currentSection);
      currentSection = {
        title: line.replace(/[:\-–—]/g, "").trim(),
        items: [],
      };
      continue;
    }

    // Check if this is contact info (before first section)
    if (!currentSection && !contact) {
      // Look for email, phone, LinkedIn patterns
      if (
        line.includes("@") ||
        line.includes("linkedin.com") ||
        line.includes("github.com") ||
        /^\+?\d/.test(line) ||
        line.includes("|") ||
        line.includes("·")
      ) {
        contact = line;
        continue;
      }
    }

    // Add to current section
    if (currentSection) {
      // Bullet points
      if (line.startsWith("•") || line.startsWith("-") || line.startsWith("*")) {
        currentSection.items.push({
          type: "bullet",
          text: line.replace(/^[•\-\*]\s*/, ""),
        });
      }
      // Sub-headings (job titles, company names)
      else if (line.length < 80 && !line.endsWith(".")) {
        currentSection.items.push({
          type: "subheading",
          text: line,
        });
      }
      // Regular text
      else {
        currentSection.items.push({
          type: "text",
          text: line,
        });
      }
    }
  }

  if (currentSection) sections.push(currentSection);

  return { contact, sections };
}
